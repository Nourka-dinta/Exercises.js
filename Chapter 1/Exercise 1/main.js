let x = 7;
let y = 3;

console.log(x);
console.log(y);

// Arithmetic operators

console.log(x + y);
console.log(x - y);
console.log(x * y);
console.log(x / y);
console.log(x % y);

// pre increment x
console.log("pre increment");
console.log(++x);

// post increment x
console.log("post increment")
console.log(x++);
console.log(x);

// pre decrement y
console.log("pre increment");
console.log(--y);

// post decrement y
console.log("post increment")
console.log(y--);
console.log(y);